#!/usr/bin/env node
// copy-registry.js — regenerates COPY-REGISTRY.md: the single map of every slash command → its description,
// owning feature, audience, permission gate, whether it has member-facing /help copy, and which copy.js keys
// back it. This is the backbone of the "change a command → change its public text" single-source-of-truth
// effort: it shows, at a glance, where each command's user-facing copy lives and what's still inlined.
//
// Read-only. Run from the bot dir: `node scripts/copy-registry.js` (writes COPY-REGISTRY.md).
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const features = require(path.join(ROOT, 'features'));
const copy = require(path.join(ROOT, 'copy'));

const src = fs.readFileSync(path.join(ROOT, 'index.js'), 'utf8');

// name → description for every setName().setDescription() chain (top-level commands AND subcommands both use it)
const descOf = {};
const re = /setName\((['"`])([\w-]+)\1\)\s*\.setDescription\((['"`])([\s\S]*?)\3\)/g;
let m; while ((m = re.exec(src))) if (!(m[2] in descOf)) descOf[m[2]] = m[4].replace(/\s+/g, ' ').trim();

// context-menu command names (no description in the API)
const ctx = [];
const cre = /ContextMenuCommandBuilder\(\)\s*\.setName\((['"`])([^'"`]+)\1\)/g;
while ((m = cre.exec(src))) ctx.push(m[2]);

// permission gate per command: setDefaultMemberPermissions right after the builder
const permOf = {};
const pre = /setName\((['"`])([\w-]+)\1\)[\s\S]*?setDefaultMemberPermissions\(PermissionsBitField\.Flags\.(\w+)\)/g;
while ((m = pre.exec(src))) if (!(m[2] in permOf)) permOf[m[2]] = m[3];

// copy.js: flatten to dotted keys
const copyKeys = [];
(function walk(o, pre) { for (const k of Object.keys(o)) { const v = o[k]; const key = pre ? pre + '.' + k : k;
  if (v && typeof v === 'object' && !Array.isArray(v)) walk(v, key); else copyKeys.push(key + (typeof v === 'function' ? '()' : '')); } })(copy, '');

const out = [];
out.push('# COPY-REGISTRY — single source of truth for public-facing text');
out.push('');
out.push('_Auto-generated by `node scripts/copy-registry.js`. Do not hand-edit — edit the code/copy.js and regenerate._');
out.push('');
out.push('Goal: a command\'s behaviour change and its public wording change together. This maps every command to');
out.push('its description, owning feature, audience, permission gate, whether it has member-facing `/help` copy, and');
out.push('which `copy.js` keys back it. "inline" = the copy still lives at the call site (a candidate to migrate).');
out.push('');
out.push('## Commands');
out.push('');
out.push('| Command | Feature | Audience | Perm gate | /help copy | Description |');
out.push('|---|---|---|---|---|---|');
const featOf = name => features.REGISTRY.find(r => (r.commands || []).includes(name) || (r.contexts || []).includes(name));
const rows = [];
for (const name of Object.keys(descOf)) {
  const f = featOf(name);
  if (!f) continue;   // skip option/subcommand names (they also use setName().setDescription()) — only real commands
  rows.push({ name, feat: f.key, aud: f.audience, perm: permOf[name] || '—', help: f.help ? '✅' : '—', desc: descOf[name] });
}
for (const name of ctx) { const f = featOf(name); rows.push({ name: name + ' (ctx)', feat: f ? f.key : '—', aud: f ? f.audience : '—', perm: permOf[name] || 'ctx', help: f && f.help ? '✅' : '—', desc: '(context-menu command)' }); }
rows.sort((a, b) => (a.feat + a.name).localeCompare(b.feat + b.name));
for (const r of rows) out.push(`| \`${r.name}\` | ${r.feat} | ${r.aud} | ${r.perm} | ${r.help} | ${r.desc.slice(0, 80)} |`);

out.push('');
out.push(`## copy.js keys (migrated so far — ${copyKeys.length})`);
out.push('');
for (const k of copyKeys.sort()) out.push(`- \`copy.${k}\``);

out.push('');
out.push('## Migration status by feature');
out.push('');
out.push('Features whose user-facing strings are (partly) centralised in `copy.js` vs still inline. Sweep order: DRY');
out.push('(cross-file duplicates) and STATE-DERIVED text first, then feature-by-feature.');
out.push('');
const migrated = new Set(Object.keys(copy));
for (const r of features.REGISTRY) {
  const keys = Object.keys(copy).filter(k => k.toLowerCase().includes(r.key.toLowerCase()));
  out.push(`- **${r.key}** (${r.audience}) — ${keys.length ? 'copy.js: ' + keys.map(k => '`' + k + '`').join(', ') : '_inline (not yet migrated)_'}`);
}

fs.writeFileSync(path.join(ROOT, 'COPY-REGISTRY.md'), out.join('\n') + '\n');
console.log(`COPY-REGISTRY.md written — ${rows.length} commands, ${copyKeys.length} copy.js keys.`);
